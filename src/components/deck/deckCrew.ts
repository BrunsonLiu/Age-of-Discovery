/**
 * 甲板上该有几个水手。
 *
 * 【三段阈值，而不是"按比例四舍五入"】船员 8 人是小船的下限、40 人是大船：
 * 用比例算的话，一条 8 人船永远只有 1 个人站在甲板上，而 40 人船会站满 ——
 * 看起来都一样"少"。按绝对人数分档更符合直觉：**甲板上总得有人**，船越大越多。
 *
 * 返回 0 的情况只有一种：船上真没人了（`crew <= 0`）—— 那时候一条空船飘在海上，
 * 比什么都说明问题，不应该还站着一个水手。
 */
export function sailorCount(crew: number): number {
  if (!Number.isFinite(crew) || crew <= 0) return 0
  if (crew < 8) return 1
  if (crew < 20) return 2
  return 3
}

/**
 * 三个岗位的**姿势**（纯数据，可单测）。
 *
 * 【为什么需要】上一轮三个人只是"站着"：同样的垂手、同样的挺直 —— 从甲板上看
 * 是三根立着的木桩，只是位置不同。而"岗位"这件事恰恰是靠**身体**表达的：
 * 掌舵的人握着轮、清点的人弯着腰、瞭望的人搭着手。
 *
 * 角度约定（模型米、弧度）：
 *  · `lean` 是上身绕**髋部**的前倾，正 = 向前弯；
 *  · `armX` 是手臂绕**肩**的前后摆，负 = 向身前抬（−2.4 ≈ 手举到额头前）；
 *  · `armZ` 是手臂外张，正 = 向身体外侧；
 *  · `headTilt` 是头相对上身的俯仰（正 = 低头）。
 */
export interface SailorPose {
  lean: number
  sink: number
  armLX: number
  armRX: number
  armLZ: number
  armRZ: number
  headTilt: number
}

