/**
 * 码头上"有人"的布局数据（纯函数，不碰 DOM）。
 *
 * 【为什么要走动的影子】岸上那张远景是**画**：画里的人永远停在同一个姿势，
 * 你盯着它看十秒，画面一动不动 —— 而这里恰恰是玩家停下来看最久的一屏。
 * 上一轮接上了天光（夜/黄昏/星/雨雾），画面会随**时间**变，但一秒之内它是死的。
 * 补上走动的影子、起伏的小艇、白天的海鸥，"活着"这件事才落在秒级。
 *
 * 【为什么影子放在前景剪影里】前景（码头 + 系缆桩 + 四盏灯）是本项目自己画的 SVG，
 * 坐标是我们自己的，所以"人在码头上"这句话是真的。画里的人影我们不知道在哪儿，
 * 硬往上贴就会踩在水里或者浮在半空 —— 那比没有更糟。
 *
 * 【为什么位置写死（种子生成）而不是随机】每次进岸上都换一批人，等于"岸上换了人"
 * 却没有任何事发生。固定下来，玩家第二次来能认出"还是那几个人"。
 */

export interface QuayWalker {
  /** 出发点（SVG viewBox 坐标，1440×164） */
  x: number
  /** 脚踩的那条线（码头面 y=122） */
  y: number
  /**
   * 身高（viewBox 单位）。**实测：26~34 读成"针尖"** —— 脚埋进纯黑的近景甲板，
   * 只有肩以上露在水面上，看上去像几根黑刺。要读成"人"得有 46~62，
   * 并且整体比甲板（#0b0704）**稍亮一档**，否则黑压黑还是看不见。
   */
  h: number
  /** 走多远（正数 = 向右，负数 = 向左） */
  span: number
  /** 一趟走完多少秒 */
  sec: number
  /** 负延迟：进场时就已经走在半路上，不会五个人同时从左边出发 */
  delay: number
}

/** mulberry32：与项目其它程序化内容同一套（固定种子可复现） */
function mulberry32(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/**
 * 码头上的五个影子。
 *
 * 三条硬约束（单测守着）：
 *  · **不下水**：脚线固定在码头面（122）上下 2px 内；
 *  · **不挡灯**：x 从 130 起 —— 第一盏灯在 x=107，它脚下那一小块是
 *    "夜里灯真的照亮了地面"的取景处（harbor-mood e2e 在这一带量亮度），
 *    影子踩上去会让那个读数忽高忽低；
 *  · **不出画**：最右侧只到 1320，右边 x≈1368 是那根桅杆。
 */
export function quayWalkers(seed = 20261113): QuayWalker[] {
  const rnd = mulberry32(seed)
  const out: QuayWalker[] = []
  const N = 5
  for (let i = 0; i < N; i++) {
    // 五个人的出发点在 130~1290 之间**均匀铺开**再加抖动：
    // 纯随机会出现两个人叠在一起（屏幕上是一条腿、两个头）
    const slot = 130 + (i + 0.5) * ((1290 - 130) / N)
    const x = slot + (rnd() - 0.5) * 90
    const dir = i % 2 === 0 ? 1 : -1
    const span = dir * (70 + rnd() * 90)
    out.push({
      x: Math.round(x),
      // 脚必须踩在码头面上沿（y=122）：那是我们自己那块近景甲板与画的交界线，
      // 人站在这里，就是"站在我们和城之间"——轮廓衬在水面和城上才看得清。
      // 脚踩在甲板上沿（y=122）：身体整段衬在**水面与城**上（那里比甲板亮得多），
      // 轮廓才立得住；沉进甲板里就变成黑压黑的几根柱子。
      /*
       * 脚在甲板上沿附近（122~127，带一点纵深抖动）：五个人脚踩同一条线会读成
       * "一排站队"。身高 38~50 比画里那些人（约 35px）略大 —— 他们在**近景**，
       * 比画里的远人还小就是透视错了。
       */
      y: 122 + Math.round(rnd() * 5),
      h: Math.round(38 + rnd() * 12),
      span: Math.round(span),
      sec: Math.round(24 + rnd() * 16),
      delay: -Math.round(rnd() * 20),
    })
  }
  return out
}

/*
 * 【删掉的东西：泊在码头下沿的小艇】
 * 试过 y=132（落在纯黑甲板里，看不见）和 y=119（骑在甲板上沿，只露出 3px）。
 * 近景甲板本身就是纯黑，黑船的轮廓立不住 —— 而且"我家船就拴在脚下"这事儿
 * 玩家本来就看不见（他在岸上，船停在外海）。留一个看不见的元素比不留更糟。
 */

/**
 * 白天的三只海鸥。
 *
 * 高度按**水面**放（y 0.52~0.66 是海面那一带，见 harbor-mood 的分区取样），
 * 不放到天空：画里的云是静态的，鸟飞在静止的云里反而更假。
 */
export function quayGulls(seed = 7717): { x: number; y: number; s: number; sec: number; delay: number }[] {
  const rnd = mulberry32(seed)
  const out: { x: number; y: number; s: number; sec: number; delay: number }[] = []
  for (let i = 0; i < 3; i++) {
    out.push({
      x: 180 + Math.round(rnd() * 420),
      y: 0.50 + rnd() * 0.08,
      s: 1.15 + rnd() * 0.45,
      sec: 46 + Math.round(rnd() * 26),
      delay: -Math.round(rnd() * 40),
    })
  }
  return out
}
